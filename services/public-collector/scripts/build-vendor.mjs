import { cp, mkdir, readFile, readdir, rename, rm, symlink, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const collectorRoot = resolve(scriptDir, "..");
const vendorRoot = join(collectorRoot, "vendor", "api-anything");
const distDir = join(vendorRoot, "dist");
const compiler = join(collectorRoot, "node_modules", "typescript", "bin", "tsc");
const patchPath = join(collectorRoot, "patches", "api-anything-runtime.patch");
const patchBytes = await readFile(patchPath);
const pinnedBytes = await readFile(join(collectorRoot, "templates", "PINNED.json"));
const pinnedSha256 = createHash("sha256").update(pinnedBytes).digest("hex");
await writeFile(join(collectorRoot, "src", "pin-hash.ts"), `// Generated by scripts/build-vendor.mjs from templates/PINNED.json.\nexport const PIN_REGISTRY_SHA256 = "${pinnedSha256}";\n`, "utf8");
const patchSha256 = createHash("sha256").update(patchBytes).digest("hex");
if (patchSha256 !== "5409be5220c92fc6c6b2d5d6acc2ca819983a61f3204403ab5a58c175f0431cc") throw new Error("VENDOR_PATCH_HASH_MISMATCH");
const buildRoot = join(collectorRoot, ".vendor-build", "api-anything");
await rm(buildRoot, { recursive: true, force: true });
await mkdir(buildRoot, { recursive: true });
await cp(join(vendorRoot, "src"), join(buildRoot, "src"), { recursive: true });
await cp(join(vendorRoot, "package.json"), join(buildRoot, "package.json"));
await cp(join(vendorRoot, "package-lock.json"), join(buildRoot, "package-lock.json"));
await cp(join(vendorRoot, "tsconfig.build.json"), join(buildRoot, "tsconfig.build.json"));
await cp(join(vendorRoot, "tsconfig.json"), join(buildRoot, "tsconfig.json"));
await symlink(join(vendorRoot, "node_modules"), join(buildRoot, "node_modules"), "junction");
const reset = spawnSync("git", ["apply", "--reverse", "--whitespace=nowarn", patchPath], {
  cwd: buildRoot,
  stdio: "inherit",
  shell: false,
});
if (reset.error) throw reset.error;
if (reset.status !== 0) process.exit(reset.status ?? 1);
const applied = spawnSync("git", ["apply", "--whitespace=nowarn", patchPath], {
  cwd: buildRoot,
  stdio: "inherit",
  shell: false,
});
if (applied.error) throw applied.error;
if (applied.status !== 0) process.exit(applied.status ?? 1);
const executeSource = await readFile(join(buildRoot, "src", "execute.ts"), "utf8");
if (/reimportIfBrowser|from ["']\.\/import\.js["']/.test(executeSource)) {
  throw new Error("OWNER_BROWSER_IMPORT_PATH_PRESENT");
}
const built = spawnSync(process.execPath, [compiler, "-p", join(buildRoot, "tsconfig.build.json")], {
  cwd: buildRoot,
  stdio: "inherit",
  shell: false,
});
if (built.error) throw built.error;
if (built.status !== 0) process.exit(built.status ?? 1);
await rm(distDir, { recursive: true, force: true });
await rename(join(buildRoot, "dist"), distDir);
const runtimeFiles = [];
async function collectFiles(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) await collectFiles(path);
    else runtimeFiles.push(path);
  }
}
await collectFiles(distDir);
runtimeFiles.sort();
const runtimeHash = createHash("sha256");
for (const file of runtimeFiles) {
  runtimeHash.update(file.slice(distDir.length + 1).replaceAll("\\", "/"));
  runtimeHash.update("\0");
  runtimeHash.update(await readFile(file));
  runtimeHash.update("\0");
}
await writeFile(join(collectorRoot, "runtime-manifest.json"), JSON.stringify({
  schema_version: 1,
  api_anything_commit: "fe5cca70fe145634e49a1c9ba1f3e8250b291bea",
  vendor_patch_sha256: patchSha256,
  playwright_core: "1.63.0",
  node_minimum: ">=22.13.0",
  runtime_file_count: runtimeFiles.length,
  runtime_sha256: runtimeHash.digest("hex"),
  pin_registry_sha256: pinnedSha256,
}, null, 2) + "\n", "utf8");
await rm(join(collectorRoot, ".vendor-build"), { recursive: true, force: true });
